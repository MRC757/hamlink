"""The HamLink logo: a lattice radio tower topped by a triangle with an eye, sending out rays, black on gold.
One list of shapes (on the 108 x 108 Android adaptive-icon canvas, kept inside its 66 x 66 safe zone) produces every
copy, so they always match:

    python tools/make_icon.py            # writes all of them:
      android/app/src/main/res/drawable/ic_launcher_foreground.xml   launcher icon (vector, flat gold background)
      ../fastlane/metadata/android/en-US/images/icon.png             512 px store icon (with a soft glow)
      windows/src/HamLink.ico                                        Windows app icon (16-256 px)
      docs/logo.png                                                  256 px, for the README

Needs Pillow (pip install pillow).
"""
import math
import os

from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                        # hamlink/

GOLD = "#E5A619"         # background (also res/values/ic_launcher_background.xml)
GOLD_LIGHT = "#F7C64A"   # glow centre (PNG only)
GOLD_DARK = "#8A5A06"    # glow edge (PNG only)
BLACK = "#16130C"
RAY = "#FFF1BF"
SCLERA = "#FFF6DC"

# ---------------------------------------------------------------- the design (108 x 108 units)
CX, EYE_Y = 54.0, 41.0
TRI = [(54, 21), (37.5, 50), (70.5, 50)]            # apex, base left, base right
LEGS_TOP, LEGS_BOT, TOP_Y, BOT_Y = (48.5, 59.5), (39, 69), 50.0, 87.0
RUNGS = [50.0, 61.0, 73.0, 87.0]                    # horizontal braces (tower widens downward)
STROKE = 2.6


def leg_x(y, side):
    """x of the left (side 0) or right (side 1) tower leg at height y."""
    t = (y - TOP_Y) / (BOT_Y - TOP_Y)
    return LEGS_TOP[side] + (LEGS_BOT[side] - LEGS_TOP[side]) * t


def shapes():
    """("line", x1, y1, x2, y2, width, colour) | ("poly", [(x, y)...], colour) | ("circle", x, y, r, colour)."""
    out = []
    # rays: around the triangle, upward and sideways (the tower takes the bottom)
    for k in range(13):
        a = math.radians(-180 + 15 * k)             # -180 .. 0 degrees: left, up, right
        r1, r2 = 21.0, 27.5 if k % 2 == 0 else 25.0
        out.append(("line", CX + r1 * math.cos(a), 38 + r1 * math.sin(a),
                    CX + r2 * math.cos(a), 38 + r2 * math.sin(a), 1.4, RAY))
    # tower: legs, rungs, X braces
    for side in (0, 1):
        out.append(("line", leg_x(TOP_Y, side), TOP_Y, leg_x(BOT_Y, side), BOT_Y, STROKE, BLACK))
    for y in RUNGS:
        out.append(("line", leg_x(y, 0), y, leg_x(y, 1), y, STROKE * 0.9, BLACK))
    for y1, y2 in zip(RUNGS, RUNGS[1:]):
        out.append(("line", leg_x(y1, 0), y1, leg_x(y2, 1), y2, STROKE * 0.75, BLACK))
        out.append(("line", leg_x(y1, 1), y1, leg_x(y2, 0), y2, STROKE * 0.75, BLACK))
    out.append(("line", 37, BOT_Y, 71, BOT_Y, STROKE, BLACK))          # ground
    # the triangle, then the eye: an almond, the iris, a highlight
    out.append(("poly", TRI, BLACK))
    almond = [(45 + 18 * t, EYE_Y - 8.5 * math.sin(math.pi * t) * 0.85) for t in (i / 24 for i in range(25))]
    almond += [(63 - 18 * t, EYE_Y + 8.5 * math.sin(math.pi * t) * 0.85) for t in (i / 24 for i in range(1, 24))]
    out.append(("poly", almond, SCLERA))
    out.append(("circle", CX, EYE_Y, 4.0, BLACK))
    out.append(("circle", CX + 1.5, EYE_Y - 1.5, 1.1, SCLERA))
    return out


# ---------------------------------------------------------------- Android vector drawable
def vector_xml():
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- HamLink logo: a lattice radio tower topped by a triangle with an eye. GENERATED by tools/make_icon.py:',
             '     edit the shapes there, not here. 108 x 108 adaptive-icon canvas on @color/ic_launcher_background. -->',
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
    for s in shapes():
        if s[0] == "line":
            _, x1, y1, x2, y2, w, c = s
            lines.append(f'    <path android:strokeColor="{c}" android:strokeWidth="{w:.2f}" android:strokeLineCap="round" '
                         f'android:pathData="M{x1:.2f},{y1:.2f} L{x2:.2f},{y2:.2f}" />')
        elif s[0] == "poly":
            _, pts, c = s
            d = "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + " Z"
            lines.append(f'    <path android:fillColor="{c}" android:pathData="{d}" />')
        else:
            _, x, y, r, c = s
            lines.append(f'    <path android:fillColor="{c}" android:pathData="M{x - r:.2f},{y:.2f} '
                         f'a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0" />')
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- PNG
def png(size, zoom=1.0, glow=True, rounded=True):
    ss = 4
    n = size * ss
    k = n / 108.0

    def P(x, y):                                     # canvas units -> pixels, zoomed around the centre (54, 54)
        return ((54 + (x - 54) * zoom) * k, (54 + (y - 54) * zoom) * k)

    bg = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    if glow:                                         # radial gold glow, like the original artwork
        yy, xx = [v.reshape(-1) for v in __import__("numpy").mgrid[0:n, 0:n]]
        import numpy as np
        d = np.sqrt((xx - n * 0.5) ** 2 + (yy - n * 0.42) ** 2) / (n * 0.72)
        d = np.clip(d, 0, 1)[:, None]
        c0 = np.array(Image.new("RGB", (1, 1), GOLD_LIGHT).getpixel((0, 0)), float)
        c1 = np.array(Image.new("RGB", (1, 1), GOLD_DARK).getpixel((0, 0)), float)
        rgb = (c0 * (1 - d ** 1.6) + c1 * d ** 1.6).astype(np.uint8).reshape(n, n, 3)
        bg = Image.fromarray(rgb, "RGB").convert("RGBA")
    else:
        bg = Image.new("RGBA", (n, n), GOLD)
    mask = Image.new("L", (n, n), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, n - 1, n - 1], radius=int(n * 0.18) if rounded else 0, fill=255)
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    img.paste(bg, (0, 0), mask)
    g = ImageDraw.Draw(img)
    for s in shapes():
        if s[0] == "line":
            _, x1, y1, x2, y2, w, c = s
            a, b = P(x1, y1), P(x2, y2)
            ww = w * zoom * k
            g.line([a, b], fill=c, width=max(1, int(ww)))
            for p in (a, b):
                g.ellipse([p[0] - ww / 2, p[1] - ww / 2, p[0] + ww / 2, p[1] + ww / 2], fill=c)
        elif s[0] == "poly":
            _, pts, c = s
            g.polygon([P(x, y) for x, y in pts], fill=c)
        else:
            _, x, y, r, c = s
            cx, cy = P(x, y)
            rr = r * zoom * k
            g.ellipse([cx - rr, cy - rr, cx + rr, cy + rr], fill=c)
    return img.resize((size, size), Image.LANCZOS)


def main():
    targets = {
        os.path.join(ROOT, "android", "app", "src", "main", "res", "drawable", "ic_launcher_foreground.xml"): None,
        os.path.join(os.path.dirname(ROOT), "fastlane", "metadata", "android", "en-US", "images", "icon.png"): 512,
        os.path.join(ROOT, "docs", "logo.png"): 256,
    }
    for path, size in targets.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        if size is None:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(vector_xml())
        else:
            png(size, zoom=1.15).save(path)
        print("wrote", os.path.relpath(path, os.path.dirname(ROOT)))
    ico = os.path.join(ROOT, "windows", "src", "HamLink.ico")
    # small Windows sizes: no glow (it muddies 16 px) and a slightly larger drawing
    big = png(256, zoom=1.2)
    big.save(ico, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    print("wrote", os.path.relpath(ico, os.path.dirname(ROOT)))


if __name__ == "__main__":
    main()
